def _o(r, *alts):
    out = []
    for x in (r, *alts, r + 10, r * 2, r + 1, r + 2):
        if x not in out and (not isinstance(x, (int, float)) or x >= 0):
            out.append(x)
    return out[:4]


def num(q_en, q_bn, r, ex_en, ex_bn, *alts, unit_en="", unit_bn=""):
    o = _o(r, *alts)
    fmt = lambda x: f"{x:,}" if isinstance(x, int) else str(x)
    return mcq(q_en, [fmt(x) + unit_en for x in o], 0, ex_en, q_bn, [fmt(x) + unit_bn for x in o], ex_bn)


def tri(b, h, what_en, what_bn):
    r = b * h // 2
    return num(f"{what_en} has a base of {b} m and a height of {h} m. What is its area?",
               f"{what_bn}-এর ভূমি {b} m আর উচ্চতা {h} m। ক্ষেত্রফল কত?", r,
               f"Triangle area = ½ x base x height = ½ x {b} x {h} = {r} m².",
               f"ত্রিভুজের ক্ষেত্রফল = ½ x ভূমি x উচ্চতা = ½ x {b} x {h} = {r} m²।",
               b * h, b + h, unit_en=" m²", unit_bn=" m²")


def cuboid(l, w, h, what_en, what_bn):
    r = l * w * h
    return num(f"{what_en} is {l} m long, {w} m wide and {h} m deep. What is its volume?",
               f"{what_bn} {l} m লম্বা, {w} m চওড়া আর {h} m গভীর। আয়তন কত?", r,
               f"Volume = length x width x height = {l} x {w} x {h} = {r} m³.",
               f"আয়তন = দৈর্ঘ্য x প্রস্থ x উচ্চতা = {l} x {w} x {h} = {r} m³।",
               l * w + h, l + w + h, 2 * (l * w + w * h + l * h), unit_en=" m³", unit_bn=" m³")


def scale(cm, ratio, what_en, what_bn):
    r = cm * ratio // 100
    return num(f"On a 1 : {ratio:,} drawing, {what_en} measures {cm} cm. How long is it in real life?",
               f"1 : {ratio:,} মাপের নকশায় {what_bn} {cm} cm। বাস্তবে কত লম্বা?", r,
               f"Real length = {cm} x {ratio:,} = {cm * ratio:,} cm = {r:,} m.",
               f"বাস্তব দৈর্ঘ্য = {cm} x {ratio:,} = {cm * ratio:,} cm = {r:,} m।",
               cm * ratio, r * 10, cm, unit_en=" m", unit_bn=" m")


def share(total, a, b, who_en, who_bn):
    part = total // (a + b)
    r = part * a
    return num(f"Rs {total:,} is shared between {who_en} in the ratio {a} : {b}. How much does the first get?",
               f"{total:,} টাকা {who_bn} মধ্যে {a} : {b} অনুপাতে ভাগ হলো। প্রথমজন কত পান?", r,
               f"Total parts = {a} + {b} = {a + b}; one part = {total:,} ÷ {a + b} = {part:,}; {a} parts = {r:,}.",
               f"মোট ভাগ = {a} + {b} = {a + b}; এক ভাগ = {total:,} ÷ {a + b} = {part:,}; {a} ভাগ = {r:,}।",
               part * b, total // a, part, unit_en="", unit_bn="")


def mean(vals, what_en, what_bn):
    r = sum(vals) // len(vals)
    v = ", ".join(str(x) for x in vals)
    return num(f"{what_en}: {v}. What is the mean?", f"{what_bn}: {v}। গড় কত?", r,
               f"Add them: {sum(vals)}; divide by {len(vals)}: {r}.",
               f"যোগ করো: {sum(vals)}; {len(vals)} দিয়ে ভাগ করো: {r}।",
               sum(vals), max(vals) - min(vals), sorted(vals)[len(vals) // 2] + 3)


def hcf(a, b):
    r = gcd(a, b)
    return num(f"What is the highest common factor (HCF) of {a} and {b}?", f"{a} আর {b}-এর গসাগু কত?", r,
               f"The biggest number that divides both {a} and {b} exactly is {r}.",
               f"{a} আর {b} দুটোকেই নিঃশেষে ভাগ করে এমন বৃহত্তম সংখ্যা {r}।",
               a * b // r, r * 2, r // 2 if r > 2 else r + 3)


def lcm(a, b):
    r = a * b // gcd(a, b)
    return num(f"Two buses leave a bridge every {a} and {b} minutes. They leave together now. After how many minutes do they next leave together?",
               f"দুটো বাস সেতু থেকে প্রতি {a} আর {b} মিনিটে ছাড়ে। এখন একসঙ্গে ছাড়ল। কত মিনিট পরে আবার একসঙ্গে ছাড়বে?", r,
               f"Find the lowest common multiple (LCM) of {a} and {b}: {r} minutes.",
               f"{a} আর {b}-এর লসাগু বের করো: {r} মিনিট।",
               a * b if a * b != r else r + a, a + b, gcd(a, b))


def pct(p, n, q_en, q_bn):
    r = n * p // 100
    return num(q_en.format(p=p, n=n), q_bn.format(p=p, n=n), r,
               f"{p}% of {n:,} = {n:,} x {p} ÷ 100 = {r:,}.",
               f"{n:,}-এর {p}% = {n:,} x {p} ÷ 100 = {r:,}।", n - r, p, r + p)


