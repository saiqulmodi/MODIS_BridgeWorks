from . import mcq


def _opts(r, near):
    out = [r]
    for d in near + (1, -1, 10, -10, 2, 100):
        if len(out) == 4:
            break
        if r + d >= 0 and r + d not in out:
            out.append(r + d)
    return [str(o) for o in out]


def calc(q_en, q_bn, r, ex_en, ex_bn, near=(10, -10, 1)):
    o = _opts(r, near)
    return mcq(q_en, o, 0, ex_en, q_bn, o, ex_bn)


def add3(a, b, q_en, q_bn):
    return calc(q_en.format(a=a, b=b), q_bn.format(a=a, b=b), a + b,
                f"{a} + {b} = {a + b}. Add ones, then tens, then hundreds, carrying when needed.",
                f"{a} + {b} = {a + b}। আগে একক, তারপর দশক, তারপর শতক যোগ করো, দরকারে হাতে রেখে।", (10, 100, -10))


def sub3(a, b, q_en, q_bn):
    return calc(q_en.format(a=a, b=b), q_bn.format(a=a, b=b), a - b,
                f"{a} - {b} = {a - b}. Check: {a - b} + {b} = {a}.",
                f"{a} - {b} = {a - b}। মিলিয়ে দেখো: {a - b} + {b} = {a}।", (10, 100, -10))


def times(a, b, q_en, q_bn):
    return calc(q_en.format(a=a, b=b), q_bn.format(a=a, b=b), a * b,
                f"{a} x {b} = {a * b}.", f"{a} x {b} = {a * b}।", (a, b, -a))


def share(t, n, q_en, q_bn):
    q, r = divmod(t, n)
    ans = f"{q} r {r}" if r else str(q)
    opts = [ans, f"{q + 1} r {r}" if r else str(q + 1), f"{q} r {r + 1}" if r and r + 1 < n else str(q - 1), str(q * n)]
    opts = list(dict.fromkeys(opts))
    while len(opts) < 4:
        opts.append(str(q + len(opts) + 1))
    ex_r_en = f" with {r} left over" if r else ""
    ex_r_bn = f", {r}টি বাকি থাকে" if r else ""
    return mcq(q_en.format(t=t, n=n), opts, 0,
               f"{t} ÷ {n} = {q}{ex_r_en}, because {q} x {n} = {q * n}.",
               q_bn.format(t=t, n=n), opts,
               f"{t} ÷ {n} = {q}{ex_r_bn}, কারণ {q} x {n} = {q * n}।")


